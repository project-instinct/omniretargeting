"""Run the unchanged production pipeline on fixed flat-ground A/B/C/D clips.

Example (from repository root):
  .venv/bin/python scripts/motion_quality_ablation.py --frames 16 --output out/quality

Window selection is source-only and recorded. It supplies candidate clips, not
action labels verified by a human. No source lifting/scaling/filtering is used.
"""

import argparse
import hashlib
import json

# OMNI_ABLATION_PACKAGE selects an immutable package snapshot for comparisons.
import os
import sys
from collections import Counter
from contextlib import redirect_stderr, redirect_stdout
from copy import deepcopy
from pathlib import Path
from time import perf_counter

import numpy as np
from scipy.spatial import Delaunay

sys.path.insert(
    0, os.environ.get("OMNI_ABLATION_PACKAGE", str(Path(__file__).resolve().parents[1]))
)

import itertools

from omniretargeting.core import OmniRetargeter
from omniretargeting.data_sources.smplx import SmplxDataSource
from omniretargeting.main import create_flat_terrain, select_mapped_source_base_pose
from omniretargeting.robot_config import load_robot_config
from omniretargeting.utils import get_adjacency_list, sample_points_on_mesh


def digest(array):
    return hashlib.sha256(np.ascontiguousarray(array).tobytes()).hexdigest()


def select_windows(positions, names, count):
    p = {n: positions[:, i] for i, n in enumerate(names)}
    height = (p["L_Wrist"][:, 2] + p["R_Wrist"][:, 2]) / 2 - p["Spine3"][:, 2]
    near = -np.linalg.norm(p["L_Wrist"] - p["R_Wrist"], axis=1)
    upper, lower = p["L_Knee"] - p["L_Hip"], p["L_Ankle"] - p["L_Knee"]
    bend = -np.sum(upper * lower, axis=1) / np.maximum(
        np.linalg.norm(upper, axis=1) * np.linalg.norm(lower, axis=1), 1e-8
    )
    fast = np.r_[
        0.0,
        np.linalg.norm(np.diff(positions - p["Pelvis"][:, None], axis=0), axis=(1, 2)),
    ]
    return {
        label: max(0, min(int(np.argmax(score)) - count // 2, len(positions) - count))
        for label, score in (
            ("raised_hands", height),
            ("bent_knee", bend),
            ("hands_near", near),
            ("fast_limbs", fast),
        )
    }


def slice_markers(markers, selection, length):
    return {
        name: {
            key: (
                value[selection].copy()
                if isinstance(value, np.ndarray) and value.ndim and len(value) == length
                else deepcopy(value)
            )
            for key, value in marker.items()
        }
        for name, marker in markers.items()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--motion", type=Path, default=Path("test_data/c167_1530_final_v3/smplx_amass.npz")
    )
    parser.add_argument("--model-directory", default="assets/body_models")
    parser.add_argument(
        "--robot-config",
        type=Path,
        default=Path("robot_models/unitree_g1/unitree_g1_instinctmj.json"),
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--frames", type=int, default=16)
    parser.add_argument(
        "--stride",
        type=int,
        default=1,
        help="Source sample spacing; cadence becomes source fps / stride",
    )
    parser.add_argument(
        "--window", action="append", help="label:start; repeat for explicit windows"
    )
    parser.add_argument(
        "--variants", nargs="+", choices=list("ABCD"), default=list("ABCD")
    )
    parser.add_argument("--kappa", type=float, default=3.0)
    parser.add_argument(
        "--source-cache",
        type=Path,
        help="Optional local cache generated by this script",
    )
    args = parser.parse_args()
    if args.frames < 4 or args.stride < 1:
        parser.error("--frames must be at least 4 for temporal measurements")
    args.output.mkdir(parents=True, exist_ok=True)
    profile = load_robot_config(args.robot_config)
    source_file_hash = hashlib.sha256(args.motion.read_bytes()).hexdigest()
    if args.source_cache and args.source_cache.exists():
        import pickle

        with args.source_cache.open("rb") as file:
            cached = pickle.load(file)
        if cached["source_file_sha256"] != source_file_hash or cached[
            "model_directory"
        ] != str(Path(args.model_directory).resolve()):
            raise ValueError(
                "Source cache does not match the requested motion/model directory"
            )
        motion = cached["motion"]
        if motion.metadata.get("frame_id_semantics", "timeline") != "timeline":
            raise ValueError(
                "Source cache must use the same default timeline adapter as this runner"
            )
    else:
        motion = SmplxDataSource(
            args.motion, model_directory=args.model_directory
        ).load()
        if args.source_cache:
            import pickle

            with args.source_cache.open("wb") as file:
                pickle.dump(
                    {
                        "source_file_sha256": source_file_hash,
                        "model_directory": str(Path(args.model_directory).resolve()),
                        "motion": motion,
                    },
                    file,
                )
    source_hash = digest(motion.positions)
    windows = (
        {x.split(":")[0]: int(x.split(":")[1]) for x in args.window}
        if args.window
        else select_windows(
            motion.positions, motion.target_names, args.frames * args.stride
        )
    )
    fps = motion.framerate / args.stride
    floor_path = args.output / "flat_ground.ply"
    floor = create_flat_terrain()
    floor.export(floor_path)
    import omniretargeting

    package_root = Path(omniretargeting.__file__).resolve().parent
    package_hashes = {
        str(p.relative_to(package_root)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(package_root.rglob("*.py"))
    }
    manifest = {
        "source": str(args.motion.resolve()),
        "source_file_sha256": source_file_hash,
        "source_positions_sha256": source_hash,
        "source_fps": motion.framerate,
        "fps": fps,
        "stride": args.stride,
        "frames": args.frames,
        "windows": windows,
        "robot_profile": str(args.robot_config.resolve()),
        "robot_model": str(profile["urdf_path"]),
        "robot_scale": 1.0,
        "scene_scale": 1.0,
        "kappa_inverse_m": args.kappa,
        "source_kind": "real_smplx",
        "window_labels": "source-feature candidates; not human-verified action classes",
        "package_root": str(package_root),
        "package_sha256": package_hashes,
    }
    (args.output / "manifest.json").write_text(json.dumps(manifest, indent=2))
    for label, start in windows.items():
        stop = start + args.frames * args.stride
        if not 0 <= start < stop <= len(motion.positions):
            raise ValueError("Requested window outside the immutable source timeline")
        sl = slice(start, stop, args.stride)
        for variant in args.variants:
            stem = args.output / f"{label}_{variant}"
            started = perf_counter()
            with (
                stem.with_suffix(".log").open("w", buffering=1) as log,
                redirect_stdout(log),
                redirect_stderr(log),
            ):
                cfg = deepcopy(profile.get("retargeting", {}))
                priority = cfg.setdefault("end_effector_priority", {})
                priority.setdefault("pose_initialization", {})["enabled"] = (
                    variant in "BD"
                )
                priority.setdefault("interaction_mesh", {}).update(
                    weighting="exponential" if variant in "CD" else "uniform",
                    kappa=args.kappa,
                )
                core = OmniRetargeter(
                    robot_urdf_path=profile["urdf_path"],
                    terrain_mesh_path=floor_path,
                    joint_mapping=profile["joint_mapping"],
                    robot_height=profile.get("robot_height"),
                    smplx_joint_names=motion.target_names,
                    height_estimation=profile.get("height_estimation"),
                    base_orientation=profile.get("base_orientation"),
                    retargeting=cfg,
                )
                anchor = profile.get("base_orientation", {}).get(
                    "root_position", "Pelvis"
                )
                priority = core.retargeting_config["end_effector_priority"]
                priority["_position_anchor_source_joint"] = anchor
                mapped = select_mapped_source_base_pose(
                    motion,
                    core.robot_model,
                    profile["joint_mapping"],
                    position_source=anchor,
                )
                if mapped is None:
                    raise ValueError(
                        "Source lacks the production mapped-base calibration"
                    )
                base, translations, base_name = mapped
                priority["_base_orientation_source_joint"] = base_name
                meta = motion.metadata
                framewise = []
                original_perform = core._perform_retargeting

                def capture(
                    *a, original_perform=original_perform, framewise=framewise, **k
                ):
                    result = original_perform(*a, **k)
                    framewise.append(result.copy())
                    return result

                core._perform_retargeting = capture
                solve_start = perf_counter()
                _, final = core.retarget_motion(
                    motion.positions[sl].copy(),
                    base_orientations=base[sl].copy(),
                    base_translations=translations[sl].copy(),
                    source_joint_orientations=meta["joint_orientations"][sl].copy(),
                    source_reference_joint_orientations=meta.get(
                        "joint_rest_orientations"
                    ),
                    source_reference_joint_positions=meta.get("joint_rest_positions"),
                    framerate=fps,
                    visualize_trajectory=False,
                    enable_terrain_scaling=False,
                    end_effector_markers=slice_markers(
                        meta["end_effector_markers"], sl, len(motion.positions)
                    ),
                )
                solve_seconds = perf_counter() - solve_start
                raw = getattr(core, "last_framewise_motion", framewise[-1])
                np.savez_compressed(
                    stem.with_suffix(".npz"),
                    framewise=raw,
                    postprocessed=final,
                    source=motion.positions[sl],
                    source_frame_ids=np.arange(start, stop, args.stride),
                    fps=fps,
                )
                # Load metrics from this checkout even when running the saved baseline package.
                import importlib.util

                spec = importlib.util.spec_from_file_location(
                    "quality_metrics",
                    Path(__file__).resolve().parents[1]
                    / "omniretargeting/motion_quality.py",
                )
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
                measured = {}
                from omniretargeting.trajectory_refinement import (
                    measure_scene_penetration,
                )

                for stage, values in (("framewise", raw), ("postprocessed", final)):
                    measured[stage] = module.trajectory_metrics(
                        core.robot_model,
                        values,
                        motion.positions[sl],
                        motion.target_names,
                        core.valid_joint_mapping,
                        priority,
                        core.last_end_effector_tasks,
                        fps,
                    )
                    measured[stage]["scene_penetration"] = measure_scene_penetration(
                        core.robot_model, values, core.terrain_mesh
                    )
                reports = getattr(core, "last_motion_solve_reports", [])
                frames = [frame for report in reports for frame in report["frames"]]
                timing = {
                    "retarget_motion_seconds": solve_seconds,
                    "initialization_seconds": sum(
                        f["initialization"]["seconds"] for f in frames
                    ),
                    "full_solve_seconds": sum(f["full_solve_seconds"] for f in frames),
                    "solved_frames_including_overlay": len(frames),
                    "fallback_reasons": dict(
                        Counter(
                            f["initialization"].get("reason")
                            for f in frames
                            if f["initialization"]["status"] == "fallback"
                        )
                    ),
                    "failed_subproblems": sum(
                        f["optimization"]["failed_subproblems"] for f in frames
                    ),
                    "frames_with_failed_subproblem": sum(
                        f["optimization"]["failed_subproblems"] > 0 for f in frames
                    ),
                }
                timing["postprocessing_and_preparation_seconds"] = (
                    solve_seconds
                    - timing["initialization_seconds"]
                    - timing["full_solve_seconds"]
                )
                scene_points = sample_points_on_mesh(
                    core.terrain_mesh,
                    int(cfg.get("terrain_sample_points", 100)),
                    seed=cfg.get("terrain_sample_seed", 0),
                )
                edge_sets = []
                for points in motion.positions[sl][:, core.mapped_joint_indices]:
                    vertices = np.vstack([points, scene_points])
                    adjacency = get_adjacency_list(
                        Delaunay(vertices).simplices, len(vertices)
                    )
                    edge_sets.append(
                        {
                            (i, j)
                            for i, neighbors in enumerate(adjacency)
                            for j in neighbors
                        }
                    )
                graph_change = [
                    1 - len(a & b) / max(len(a | b), 1)
                    for a, b in itertools.pairwise(edge_sets)
                ]
                report = {
                    "variant": variant,
                    "window": [start, stop],
                    "measurements": measured,
                    "timing": timing,
                    "source_graph_edge_change_fraction": module.summary(graph_change),
                    "effective_config": core.last_effective_config,
                    "frame_reports": reports,
                    "collision_diagnostics": core.last_collision_diagnostics,
                }
                from omniretargeting.local_collision_repair import diagnostics_json

                stem.with_suffix(".json").write_text(diagnostics_json(report))
            if digest(motion.positions) != source_hash:
                raise RuntimeError("Source changed during experiment")
            print(
                f"{label} {variant}: saved {stem}; {perf_counter() - started:.1f}s",
                flush=True,
            )


if __name__ == "__main__":
    main()
